"""
generate_data.py
================
Synthetic Energy & Weather Dataset Generator for GridMate (Lonavala Testbed).

NOTE ON DATA AUTHENTICITY:
All data generated by this script is strictly SYNTHETIC and intended for prototype
development, demonstration, and offline model benchmarking. It must NOT be presented
as real measured meteorological or utility data from Lonavala.

Assumptions & Domain Modeling (Lonavala, Western Ghats ~18.75°N, 73.40°E):
1. Temporal Coverage:
   - 1 full year of hourly observations (8,760 hours): 2025-10-01 to 2026-09-30.
   - Preserves clear diurnal cycles and distinct seasonal shifts (dry winter, hot pre-monsoon,
     heavy South-West monsoon from June to September).

2. Weather Variables:
   - Solar Irradiance (GHI, W/m²): Zero at night; bell-shaped diurnal curve peaking around solar noon;
     heavily attenuated by cloud cover, particularly during monsoon.
   - Temperature (°C): Diurnal fluctuation (troughs at sunrise, peaks mid-afternoon);
     cooler in winter (14–26°C), hottest in pre-monsoon March–May (20–36°C), tempered by rain in monsoon (20–26°C).
   - Humidity (%): Inversely correlated with temperature; near saturation (85–98%) during monsoon rains.
   - Cloud Cover (0.0 to 1.0): High during monsoon (0.7–1.0), low to moderate in dry months (0.0–0.4).
   - Wind Speed (m/s): Modeled with Weibull-like distribution; monsoon months experience sustained higher winds.
   - Wind Direction (degrees): Prevailing westerly/south-westerly winds during monsoon, shifting north-easterly in winter.
   - Rainfall (mm/hr): Episodic, concentrated in monsoon months (June–September) reflecting Western Ghats precipitation.
   - Pressure (hPa): Around 940 hPa reflecting Lonavala's elevation (~624 m MSL), dipping slightly during monsoon lows.
   - Water Flow (m³/s): Hydrological proxy combining accumulated monsoon runoff with exponential reservoir discharge decay.

3. Generation & Demand Targets (in kW):
   - Solar Generation (solar_kw):
     - Peak capacity ~500 kW.
     - Function of GHI, ambient temperature coefficient (-0.4%/°C above 25°C), and panel cleanliness.
     - Strictly zero when GHI == 0.
   - Wind Generation (wind_kw):
     - Rated capacity ~250 kW.
     - Follows a standard wind turbine power curve (cut-in = 3.0 m/s, rated = 11.0 m/s, cut-out = 25.0 m/s).
   - Hydro Generation (hydro_kw):
     - Rated capacity ~300 kW.
     - Run-of-river / reservoir dispatch driven by water inflow and seasonal reservoir retention.
   - Electricity Demand (load_kw):
     - Peak demand ~1,100 kW, baseload ~450 kW.
     - Dual-peak diurnal profile (morning ~9–10 AM, evening ~7–9 PM).
     - Weekend surges (+15%) reflecting Lonavala's tourism/hospitality influx.
     - Moderate temperature-dependent cooling demand during hot pre-monsoon months.

Reproducibility:
- Fixed random seed (SEED = 42).
"""

from pathlib import Path
import numpy as np
import pandas as pd

RANDOM_SEED = 42
DATA_DIR = Path(__file__).resolve().parent
OUTPUT_CSV = DATA_DIR / "synthetic_lonavala_energy_data.csv"


def generate_synthetic_data(
    start_date: str = "2025-10-01 00:00:00",
    hours: int = 8760,
    seed: int = RANDOM_SEED,
) -> pd.DataFrame:
    """Generate 1 year of hourly synthetic weather, renewable generation, and demand data."""
    rng = np.random.default_rng(seed)

    # 1. Timestamps & Time Index
    timestamps = pd.date_range(start=start_date, periods=hours, freq="h")
    df = pd.DataFrame({"timestamp": timestamps})

    day_of_year = df["timestamp"].dt.day_of_year.to_numpy()
    hour = df["timestamp"].dt.hour.to_numpy()
    month = df["timestamp"].dt.month.to_numpy()
    day_of_week = df["timestamp"].dt.day_of_week.to_numpy()
    is_weekend = (day_of_week >= 5).astype(int)

    # Monsoon indicator (June to September in Maharashtra)
    is_monsoon = np.isin(month, [6, 7, 8, 9]).astype(float)
    # Summer indicator (March to May)
    is_summer = np.isin(month, [3, 4, 5]).astype(float)
    # Winter indicator (November to February)
    is_winter = np.isin(month, [11, 12, 1, 2]).astype(float)

    # 2. Weather Generation
    # Ambient Temperature (°C)
    # Annual cycle: peak in April/May (~32°C), dip in Jan (~20°C) and July monsoon (~23°C)
    base_temp_annual = 25.0 + 5.0 * np.sin(2 * np.pi * (day_of_year - 80) / 365.0) - 3.5 * is_monsoon
    # Diurnal cycle: minimum at 05:00, maximum at 14:00
    diurnal_temp = 5.0 * np.sin(2 * np.pi * (hour - 8) / 24.0)
    temp_noise = rng.normal(0, 1.2, size=hours)
    temperature = np.clip(base_temp_annual + diurnal_temp + temp_noise, 12.0, 40.0)

    # Cloud Cover (0.0 to 1.0)
    # High in monsoon (mean ~0.8), low in winter (mean ~0.15), moderate in summer (mean ~0.25)
    base_cloud = 0.15 * is_winter + 0.25 * is_summer + 0.78 * is_monsoon
    cloud_noise = rng.beta(2, 2, size=hours) * 0.35 - 0.15
    cloud_cover = np.clip(base_cloud + cloud_noise, 0.0, 1.0)

    # Solar Irradiance (GHI in W/m²)
    # Solar elevation profile: 0 for hour < 6 or hour > 18
    solar_angle = np.maximum(0.0, np.sin(np.pi * (hour - 6) / 12.0))
    solar_angle[hour < 6] = 0.0
    solar_angle[hour > 18] = 0.0

    # Clear sky GHI peaking around 950 W/m² in spring/summer, ~800 W/m² in winter
    clear_sky_peak = 850.0 + 100.0 * np.sin(2 * np.pi * (day_of_year - 80) / 365.0)
    # Attenuated by clouds
    cloud_transmission = (1.0 - 0.78 * (cloud_cover ** 1.3))
    ghi_noise = rng.normal(1.0, 0.04, size=hours)
    solar_irradiance = np.where(
        solar_angle > 0,
        np.clip(clear_sky_peak * solar_angle * cloud_transmission * ghi_noise, 0.0, 1050.0),
        0.0,
    )

    # Humidity (%)
    # Inversely related to temperature, heightened by monsoon
    base_humidity = 50.0 - 1.2 * (temperature - 25.0) + 38.0 * is_monsoon
    humidity_noise = rng.normal(0, 4.0, size=hours)
    humidity = np.clip(base_humidity + humidity_noise, 20.0, 100.0)

    # Rainfall (mm/hr)
    # Western Ghats monsoon: frequent rain events in Jun-Sep, near zero otherwise
    rain_probability = is_monsoon * (0.35 + 0.30 * cloud_cover) + (1.0 - is_monsoon) * 0.01
    rain_occurs = rng.uniform(0, 1, size=hours) < rain_probability
    rain_intensity = rng.exponential(scale=4.5, size=hours) * is_monsoon + rng.exponential(scale=0.5, size=hours) * (1.0 - is_monsoon)
    rainfall = np.where(rain_occurs, np.round(rain_intensity, 2), 0.0)

    # Wind Speed (m/s)
    # Modeled with a Weibull distribution; higher baseline and gusts in monsoon
    weibull_scale = 3.5 + 2.8 * is_monsoon + 0.8 * np.sin(2 * np.pi * (hour - 12) / 24.0)
    wind_speed = rng.weibull(a=2.0, size=hours) * (weibull_scale / 1.12)
    wind_speed = np.clip(wind_speed, 0.2, 22.0)

    # Wind Direction (degrees: 0-360)
    # SW monsoon (~220-260°) vs NE winter (~45-90°)
    monsoon_dir = 240.0 + rng.normal(0, 25.0, size=hours)
    dry_dir = 70.0 + rng.normal(0, 40.0, size=hours)
    wind_direction = np.where(is_monsoon == 1.0, monsoon_dir, dry_dir) % 360.0

    # Atmospheric Pressure (hPa)
    # Lonavala elevation ~624m; base pressure around 940 hPa, lower during monsoon depressions
    pressure = 942.0 - 5.0 * is_monsoon + 1.5 * np.cos(2 * np.pi * (day_of_year) / 365.0) + rng.normal(0, 1.0, size=hours)

    # Water Flow / Reservoir Inflow Proxy (m³/s)
    # Runoff accumulation during monsoon with smooth hydrological recession
    # Simulate a 72-hour moving retention of rainfall
    rain_series = pd.Series(rainfall)
    smoothed_runoff = rain_series.rolling(window=72, min_periods=1).mean().to_numpy()
    water_flow = 8.0 + 45.0 * is_monsoon + 12.0 * smoothed_runoff + rng.normal(0, 1.5, size=hours)
    water_flow = np.clip(water_flow, 4.0, 95.0)

    # 3. Energy Generation Targets (kW)
    # Solar Generation (solar_kw) - 500 kW rated farm
    solar_rated_kw = 500.0
    # Performance ratio drops slightly as temperature exceeds 25°C
    temp_derating = 1.0 - 0.004 * np.maximum(0.0, temperature - 25.0)
    solar_generation = (solar_rated_kw * (solar_irradiance / 1000.0) * temp_derating) + rng.normal(0, 2.0, size=hours)
    solar_kw = np.where(solar_irradiance > 5.0, np.clip(solar_generation, 0.0, solar_rated_kw), 0.0)

    # Wind Generation (wind_kw) - 250 kW rated farm
    wind_rated_kw = 250.0
    v_cut_in = 3.0
    v_rated = 11.0
    v_cut_out = 25.0

    wind_kw = np.zeros(hours)
    # Sub-rated power curve (cubic approximation)
    cubic_mask = (wind_speed >= v_cut_in) & (wind_speed < v_rated)
    wind_kw[cubic_mask] = wind_rated_kw * (
        (wind_speed[cubic_mask] ** 3 - v_cut_in ** 3) / (v_rated ** 3 - v_cut_in ** 3)
    )
    # Rated output
    rated_mask = (wind_speed >= v_rated) & (wind_speed < v_cut_out)
    wind_kw[rated_mask] = wind_rated_kw
    # Add small mechanical jitter
    wind_kw = np.clip(wind_kw + np.where(wind_kw > 0, rng.normal(0, 2.5, size=hours), 0.0), 0.0, wind_rated_kw)

    # Hydro Generation (hydro_kw) - 300 kW rated mini-hydro plant
    # Base load dispatch + inflow-driven generation
    hydro_rated_kw = 300.0
    hydro_generation = 65.0 + (water_flow / 95.0) * (hydro_rated_kw - 65.0) + rng.normal(0, 3.0, size=hours)
    hydro_kw = np.clip(hydro_generation, 40.0, hydro_rated_kw)

    # 4. Electricity Demand / Load (load_kw)
    # Base demand + morning peak (09:00) + evening peak (20:00) + weekend hospitality + summer cooling
    base_load = 460.0
    # Morning peak around 9 AM
    morning_peak = 220.0 * np.exp(-((hour - 9) ** 2) / 6.0)
    # Evening peak around 8 PM (20:00)
    evening_peak = 340.0 * np.exp(-((hour - 20) ** 2) / 8.0)
    # Weekend hospitality surge
    weekend_effect = 110.0 * is_weekend
    # Summer AC cooling effect
    cooling_effect = 60.0 * is_summer * np.maximum(0.0, (temperature - 28.0) / 6.0)
    # Stochastic variation
    load_noise = rng.normal(0, 15.0, size=hours)

    load_kw = base_load + morning_peak + evening_peak + weekend_effect + cooling_effect + load_noise
    load_kw = np.clip(load_kw, 350.0, 1200.0)

    # 5. Assemble Final DataFrame
    df["temperature"] = np.round(temperature, 2)
    df["humidity"] = np.round(humidity, 1)
    df["solar_irradiance"] = np.round(solar_irradiance, 2)
    df["cloud_cover"] = np.round(cloud_cover, 3)
    df["wind_speed"] = np.round(wind_speed, 2)
    df["wind_direction"] = np.round(wind_direction, 1)
    df["rainfall"] = np.round(rainfall, 2)
    df["pressure"] = np.round(pressure, 1)
    df["water_flow"] = np.round(water_flow, 2)

    # Targets (in kW)
    df["solar_kw"] = np.round(solar_kw, 2)
    df["wind_kw"] = np.round(wind_kw, 2)
    df["hydro_kw"] = np.round(hydro_kw, 2)
    df["load_kw"] = np.round(load_kw, 2)

    # Metadata tag
    df["is_synthetic"] = True

    return df


def main():
    print(f"Generating 1-year synthetic dataset for Lonavala (seed={RANDOM_SEED})...")
    df = generate_synthetic_data()

    OUTPUT_CSV.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(OUTPUT_CSV, index=False)
    print(f"Dataset successfully saved to: {OUTPUT_CSV}")
    print(f"Shape: {df.shape[0]} rows x {df.shape[1]} columns")
    print("\nTarget summary statistics (kW):")
    targets = ["solar_kw", "wind_kw", "hydro_kw", "load_kw"]
    print(df[targets].describe().round(2).to_string())


if __name__ == "__main__":
    main()
